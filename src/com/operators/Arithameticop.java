package com.operators;

//  Arithmetic operator
public class Arithameticop {

	public static void main(String[] args) {
		int a=97;
		int b=7;
		
		
		System.out.println("main method started : ");
		double d = 10.5;
		float f = 5.9f;
		System.out.println("Sum of two numbers : " +(d+f));
		System.out.println("difference two numbers : " + (d-f));
		
		System.out.println("product of two numbers : " +(d*f));
		System.out.println("quotient of two numbers : " +(a/b));
		System.out.println("remainder of two numbers : " +(a%b));
		System.out.println(5 * 4 + 7 * 5);
		System.out.println(10 / 4 + 14 % 3);
		

	}

}
