package com.operators;

public class Shiftop {

	public static void main(String[] args) {
		int num=20;
		int multiply=num<<1;
		int divide=num>>1;
		
		System.out.println("num is : " + num);
		System.out.println("multiply 2 is " + multiply);
		System.out.println("divide 2 is : " + divide);
	

	}

}
